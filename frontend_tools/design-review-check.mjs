import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
await page.goto('http://127.0.0.1:8765');
assert.equal(await page.locator('.history').count(),12);
assert(await page.locator('.personalize').isVisible());
const bounds=await page.evaluate(()=>{let s=document.querySelector('.secondary').getBoundingClientRect(),b=document.querySelector('.personalize').getBoundingClientRect();return {actual:b.y+b.height/2,expected:s.y+12+(s.height-12)/2}});
assert(Math.abs(bounds.actual-bounds.expected)<1);
await page.screenshot({path:'../design_review/desktop.png',fullPage:false});
await page.getByRole('button',{name:'Add reference',exact:true}).click();
await page.locator('[data-source="Paste link"]').click();
assert(await page.getByRole('textbox',{name:'Reference link'}).isVisible());
await page.getByRole('button',{name:'Close',exact:true}).click();
await page.getByRole('textbox',{name:'Search learning'}).fill('substitution');
assert.equal(await page.locator('.history').count(),1);
await page.getByRole('textbox',{name:'Search learning'}).fill('');
await page.getByRole('button',{name:'Personalize',exact:true}).click();
assert(await page.locator('details').evaluate(n=>n.open));
assert(await page.getByRole('textbox',{name:'Where are you stuck?'}).isEditable());
assert(await page.getByRole('textbox',{name:'Teaching style'}).isEditable());
await page.screenshot({path:'../design_review/personalization.png'});
await page.getByRole('button',{name:'Close sidebar',exact:true}).click();
await page.waitForTimeout(250);
assert(await page.locator('body').evaluate(n=>n.classList.contains('collapsed')));
await page.setViewportSize({width:390,height:844});
await page.reload();
await page.evaluate(()=>window.scrollTo(0,0));
await page.waitForTimeout(300);
assert(await page.evaluate(()=>document.documentElement.scrollWidth===innerWidth));
await page.screenshot({path:'../design_review/mobile.png'});
await page.getByRole('button',{name:'Open sidebar',exact:true}).click();
await page.waitForTimeout(250);
assert(await page.locator('.sidebar').evaluate(n=>!n.classList.contains('closed')));
await browser.close();
console.log('Passed: history/search, composer centering, link dialog, free-text personalization, sidebar, mobile overflow.');
