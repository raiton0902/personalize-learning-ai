import { chromium } from 'playwright';
import assert from 'node:assert/strict';

const browser = await chromium.launch({channel:'chrome'});
const context = await browser.newContext({viewport:{width:1440,height:900}});
await context.addInitScript(()=>sessionStorage.setItem('learning-motion-paused','true'));
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const results = [];
const check = (name, condition) => { assert.ok(condition, name); results.push(name); };
const ready = async () => {
  await page.goto('http://127.0.0.1:8502/');
  await page.waitForFunction(()=>!!window.personalLearningHome);
};
const transform = () => page.locator('.current-blue').evaluate(e=>e.style.transform);
try {
  await ready();
  check('True black ground', await page.locator('.stApp').evaluate(e=>getComputedStyle(e).backgroundColor)==='rgb(0, 0, 0)');
  const initial = await transform();
  await page.waitForTimeout(350);
  check('Background moves at rest', initial !== await transform());
  check('Pause control removed',await page.locator('#motion-toggle').count()===0);
  check('CTA is inside goal form',await page.locator('#tailor-learning').evaluate(e=>!!e.closest('[data-testid="stForm"]')));
  check('Collapsed preferences remain rendered below first screen',await page.locator('.st-key-home_details').isVisible() && await page.locator('.st-key-home_details').evaluate(e=>e.getBoundingClientRect().top>=innerHeight));
  check('Tailor is a button without an arrow',await page.getByRole('button',{name:'Tailor my learning',exact:true}).textContent().then(t=>t.trim()==='Tailor my learning'));
  const submit=page.getByRole('button',{name:'Build my learning plan',exact:true});
  check('Submit has circular dimensions',await submit.evaluate(e=>{const s=getComputedStyle(e);return Math.abs(e.offsetWidth-e.offsetHeight)<1 && s.borderRadius==='50%'}));
  check('Submit is a compact 44px circle',await submit.evaluate(e=>e.offsetWidth===44 && e.offsetHeight===44));
  check('Arrow is centered in the circle',await submit.evaluate(e=>{const s=getComputedStyle(e,'::after');return Math.abs(parseFloat(s.marginLeft)+parseFloat(s.width)/2-e.clientWidth/2)<1 && Math.abs(parseFloat(s.marginTop)+parseFloat(s.height)/2-e.clientHeight/2)<1}));
  check('Desktop title is larger',await page.getByRole('heading',{level:1}).evaluate(e=>parseFloat(getComputedStyle(e).fontSize)>=100));
  await page.screenshot({path:'../docs/screenshots/homepage-v4-desktop.png'});
  const goal = page.getByRole('textbox',{name:'Your learning goal',exact:true});
  await goal.fill('I want to understand equations.');
  const writing = await transform();
  await page.waitForTimeout(350);
  check('Curves stop while typing', writing === await transform());
  await page.getByRole('button',{name:'Tailor my learning',exact:true}).click();
  await page.waitForFunction(()=>{const y=document.querySelector('.st-key-home_details').getBoundingClientRect().top;return y>=0&&y<240});
  check('CTA opens preferences', await page.locator('.st-key-home_details details').evaluate(e=>e.open));
  check('CTA focuses disclosure', await page.locator('.st-key-home_details summary').evaluate(e=>e===document.activeElement));
  check('Pointer activation adds no blue summary outline',await page.locator('.st-key-home_details summary').evaluate(e=>getComputedStyle(e).outlineStyle==='none'));
  const top=await page.locator('.st-key-home_details').evaluate(e=>e.getBoundingClientRect().top);
  check('CTA scrolls to preferences',top>=0 && top<240);
  const settingsBox=await page.getByRole('textbox',{name:'An interest for examples',exact:true}).boundingBox();
  const previewBox=await page.locator('.lesson-preview').boundingBox();
  check('Settings and lesson preview sit side by side',previewBox.x>settingsBox.x+settingsBox.width);
  await page.waitForFunction(()=>[...document.querySelectorAll('.st-key-home_details [data-testid="stSelectbox"] input')].every(e=>e.readOnly));
  check('Choice fields have no editable text input',await page.locator('.st-key-home_details [data-testid="stSelectbox"] input:not([type="hidden"]):not([readonly]):not([disabled])').count()===0);
  check('Choice inputs have no inner border',await page.locator('.st-key-home_details [data-testid="stSelectbox"] input').evaluateAll(nodes=>nodes.every(e=>getComputedStyle(e).borderTopWidth==='0px' && getComputedStyle(e).boxShadow==='none')));
  await page.getByRole('combobox',{name:'Teaching language',exact:true}).click();
  await page.getByRole('option',{name:'Bahasa Indonesia',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.setup-preview').textContent.includes('Bahasa Indonesia'));
  check('Dropdown choice updates preview',await page.locator('.lesson-preview').innerText().then(t=>t.includes('Kurangi')));
  const languageChoice=page.getByRole('combobox',{name:'Teaching language',exact:true});
  await languageChoice.pressSequentially('zzz');
  check('Typing cannot change a choice value',await languageChoice.inputValue()==='Bahasa Indonesia');
  await page.getByRole('heading',{name:'Make it fit you',exact:true}).click();
  await page.screenshot({path:'../docs/screenshots/homepage-v4-preferences.png'});
  const interest=page.getByRole('textbox',{name:'An interest for examples',exact:true});
  await interest.fill('Music');
  await interest.press('Tab');
  await page.waitForTimeout(600);
  check('Goal survives preference rerun',await goal.inputValue()==='I want to understand equations.');
  check('Preview reflects chosen interest',await page.locator('.setup-preview').innerText().then(text=>text.includes('Music')));
  await page.locator('.st-key-home_details summary').click();
  await page.waitForFunction(()=>!document.querySelector('.st-key-home_details details').open);
  check('Disclosure can close',!await page.locator('.st-key-home_details details').evaluate(e=>e.open));
  check('Collapsed summary remains discoverable',await page.locator('.st-key-home_details summary').isVisible());
  await page.locator('.st-key-home_details summary').click();
  await page.waitForFunction(()=>document.querySelector('.st-key-home_details details').open);
  check('User can open preferences directly without Tailor',await page.getByRole('combobox',{name:'Teaching language',exact:true}).isVisible());
  await page.locator('.st-key-home_details summary').click();
  await page.getByRole('button',{name:'Tailor my learning',exact:true}).focus();
  await page.keyboard.press('Enter');
  await page.waitForFunction(()=>document.querySelector('.st-key-home_details details').open);
  check('Keyboard CTA reopens preferences',await page.locator('.st-key-home_details details').evaluate(e=>e.open));
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.waitForTimeout(100);
  const reduced=await transform();
  await page.waitForTimeout(350);
  check('Reduced motion stops curves',reduced===await transform());
  await page.emulateMedia({reducedMotion:'no-preference'});
  for (const width of [390,768,1024,1440,1920]) {
    await page.setViewportSize({width,height:900});
    check(`No horizontal overflow at ${width}px`,await page.evaluate(()=>document.querySelector('[data-testid="stMain"]').scrollWidth<=innerWidth));
  }
  for (const [width,height] of [[1440,900],[1280,630],[1920,950],[390,844],[390,640]]) {
    await page.setViewportSize({width,height});
    await ready();
    const bounds = await page.locator('#tailor-learning').boundingBox();
    const button = await page.getByRole('button',{name:'Build my learning plan',exact:true}).boundingBox();
    check(`Both actions visible on arrival at ${width}x${height}`,bounds.y>=0 && bounds.y+bounds.height<=height && button.y+button.height<=height);
    if(width===390 && height===844) await page.screenshot({path:'../docs/screenshots/homepage-v4-mobile.png'});
    await page.getByRole('button',{name:'Tailor my learning',exact:true}).click();
    await page.waitForFunction(()=>{const y=document.querySelector('.st-key-home_details').getBoundingClientRect().top;return y>=0&&y<96});
    check(`Instant open and jump at ${width}x${height}`,await page.locator('.st-key-home_details details').evaluate(e=>e.open));
    if(width===390 && height===844) await page.screenshot({path:'../docs/screenshots/homepage-v4-mobile-preferences.png'});
  }
  await page.locator('.st-key-home_secondary summary').click();
  const sessionCode=page.getByLabel('Session code',{exact:true});
  check('Session-code field has no inner white border',await sessionCode.evaluate(e=>getComputedStyle(e).borderTopWidth==='0px' && getComputedStyle(e).boxShadow==='none'));
  await page.locator('.st-key-home_secondary').screenshot({path:'../docs/screenshots/homepage-v4-session.png'});
  check('No browser JavaScript errors',errors.length===0);
  console.log(JSON.stringify({passed:results.length,checks:results,errors},null,2));
} catch (error) {
  console.error('Failure state:',await page.evaluate(()=>({panel:document.querySelector('.st-key-home_details')?.getBoundingClientRect().toJSON(),scrollTop:document.querySelector('[data-testid="stMain"]')?.scrollTop,open:document.querySelector('.st-key-home_details details')?.open})));
  throw error;
} finally { await browser.close(); }
